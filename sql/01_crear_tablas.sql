-- Crea las cinco tablas del negocio en TU esquema de Oracle (FreeSQL).
-- Se puede ejecutar de nuevo: primero borra las tablas (en orden inverso
-- a las dependencias). OJO: al hacerlo se pierden sus datos.

DROP TABLE IF EXISTS detalle_venta CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS ventas CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS medicamentos CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS clientes CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS laboratorios CASCADE CONSTRAINTS PURGE;

-- IDENTITY + NOCACHE: Oracle numera solo la PK, sin saltos de numeracion.
-- Las fechas se guardan en UTC, que es lo que espera Django.

CREATE TABLE laboratorios (
    id_laboratorio  NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    nombre          VARCHAR2(100) NOT NULL,
    pais            VARCHAR2(60)  NOT NULL,
    CONSTRAINT pk_laboratorios PRIMARY KEY (id_laboratorio),
    CONSTRAINT uq_laboratorios_nombre UNIQUE (nombre)
);

CREATE TABLE clientes (
    id_cliente      NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    rut             VARCHAR2(12)  NOT NULL,
    nombre          VARCHAR2(100) NOT NULL,
    email           VARCHAR2(100),
    telefono        VARCHAR2(20),
    fecha_registro  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_clientes PRIMARY KEY (id_cliente),
    CONSTRAINT uq_clientes_rut UNIQUE (rut),
    CONSTRAINT uq_clientes_email UNIQUE (email)
);

-- requiere_receta: NUMBER(1) con CHECK (1 = exige receta, 0 = venta libre)
CREATE TABLE medicamentos (
    id_medicamento    NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    id_laboratorio    NUMBER(11)    NOT NULL,
    codigo            VARCHAR2(30)  NOT NULL,
    nombre            VARCHAR2(120) NOT NULL,
    descripcion       CLOB,
    precio            NUMBER(10,2)  NOT NULL,
    stock             NUMBER(11)    DEFAULT 0 NOT NULL,
    requiere_receta   NUMBER(1)     DEFAULT 0 NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    CONSTRAINT pk_medicamentos PRIMARY KEY (id_medicamento),
    CONSTRAINT uq_medicamentos_codigo UNIQUE (codigo),
    CONSTRAINT fk_medicamentos_laboratorio FOREIGN KEY (id_laboratorio)
        REFERENCES laboratorios (id_laboratorio),
    CONSTRAINT ck_medicamentos_precio CHECK (precio >= 0),
    CONSTRAINT ck_medicamentos_stock CHECK (stock >= 0),
    CONSTRAINT ck_medicamentos_receta CHECK (requiere_receta IN (0, 1))
);

-- numero_receta es opcional (NULL en ventas sin medicamentos con receta).
CREATE TABLE ventas (
    id_venta        NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    id_cliente      NUMBER(11) NOT NULL,
    fecha           TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    numero_receta   VARCHAR2(30),
    total           NUMBER(12,2) DEFAULT 0 NOT NULL,
    estado          VARCHAR2(9)  DEFAULT 'pendiente' NOT NULL,
    CONSTRAINT pk_ventas PRIMARY KEY (id_venta),
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente),
    CONSTRAINT ck_ventas_estado CHECK (estado IN ('pendiente', 'pagada', 'anulada')),
    CONSTRAINT ck_ventas_total CHECK (total >= 0)
);

-- Sin id propio: la clave es la pareja (id_venta, id_medicamento).
-- subtotal es una columna VIRTUAL calculada por Oracle.
CREATE TABLE detalle_venta (
    id_venta        NUMBER(11)   NOT NULL,
    id_medicamento  NUMBER(11)   NOT NULL,
    cantidad        NUMBER(11)   NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal        NUMBER(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,
    CONSTRAINT pk_detalle_venta PRIMARY KEY (id_venta, id_medicamento),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta)
        REFERENCES ventas (id_venta) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_medicamento FOREIGN KEY (id_medicamento)
        REFERENCES medicamentos (id_medicamento),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);

-- Indices para las claves foraneas (Oracle no los crea solo)
CREATE INDEX ix_medicamentos_laboratorio ON medicamentos (id_laboratorio);
CREATE INDEX ix_medicamentos_vencimiento ON medicamentos (fecha_vencimiento);
CREATE INDEX ix_ventas_cliente ON ventas (id_cliente);
CREATE INDEX ix_detalle_medicamento ON detalle_venta (id_medicamento);